#!/usr/bin/env python3
"""Generate ChebAllxChallenge.lean from ChebAllxSolution.lean (statements) and the Mathlib-only
definitions `GRHFor`, `chi4` (inlined verbatim from ../lean-chebyshev/ChebLib/Race/Defs.lean) and
`chebyshevSum`, `chebyshevLogSum` (inlined verbatim from ../lean-chebyshev/ChebLib/Cheb/Defs.lean).

ChebAllxChallenge.lean = header + the four definitions + every theorem of ChebAllxSolution.lean
with its docstring and statement copied byte for byte and its proof replaced by `sorry`.
Also regenerates scripts/PrintAxioms.lean and comparator.json.
Run from the project root:   python3 scripts/gen_challenge.py
With --check it only verifies that the committed files are up to date (exit code 1 if not).
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
race_defs = (root / ".." / "lean-chebyshev" / "ChebLib" / "Race" / "Defs.lean").read_text()
cheb_defs = (root / ".." / "lean-chebyshev" / "ChebLib" / "Cheb" / "Defs.lean").read_text()
sol = (root / "ChebAllxSolution.lean").read_text()
header = (root / "scripts" / "challenge_header.txt").read_text()


def grab(text, start):
    """The docstring + definition starting at the docstring that precedes `start`."""
    i = text.index(start)
    j = text.rindex("/--", 0, i)
    k = text.find("\n\n", i)
    if k < 0:
        k = len(text)
    return text[j:k].rstrip("\n")


def_grh = grab(race_defs, "def GRHFor")
def_chi4 = grab(race_defs, "def chi4 ")
def_sum = grab(cheb_defs, "def chebyshevSum ")
def_logsum = grab(cheb_defs, "def chebyshevLogSum ")

pat = re.compile(r"(/--(?:.|\n)*?-/\ntheorem (\w+)(?:.|\n)*?) := by\n((?:  .*\n?)+)")
thms = pat.findall(sol)
if not thms:
    sys.exit("no theorems found in ChebAllxSolution.lean")
opens = "\n".join(l for l in sol.splitlines() if l.startswith("open "))

out = [header.rstrip("\n") + "\nimport Mathlib\n"]
out.append("/-! ## Definitions (inlined verbatim) -/\n")
out.append(def_grh + "\n")
out.append(def_chi4 + "\n")
out.append("noncomputable section\n")
out.append(def_sum + "\n")
out.append(def_logsum + "\n")
out.append("end\n")
out.append(opens + "\n")
out.append("/-! ## Statements -/\n")
names = []
for stmt, name, _proof in thms:
    names.append(name)
    out.append(stmt + " := by\n  sorry\n")
challenge = "\n".join(out)

axioms = ['''/-
scripts/PrintAxioms.lean — axiom audit of the headline theorems (GENERATED by
scripts/gen_challenge.py):
    lake build ChebAllxSolution && lake env lean scripts/PrintAxioms.lean
Every line must print exactly
    'X' depends on axioms: [propext, Classical.choice, Quot.sound]
(no sorryAx, no Lean.ofReduceBool, no other axiom).  GRH for L(s,χ₋₄) is an explicit hypothesis of
the theorems, visible in their statements; it is not an axiom.
-/
import ChebAllxSolution
''']
axioms += ["#print axioms %s" % n for n in names]
axioms_text = "\n".join(axioms) + "\n"

comparator = json.dumps({
    "challenge_module": "ChebAllxChallenge",
    "solution_module": "ChebAllxSolution",
    "theorem_names": names,
    "definition_names": ["GRHFor", "chi4", "chebyshevSum", "chebyshevLogSum"],
    "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
    "enable_nanoda": True,
}, indent=2) + "\n"

targets = {
    root / "ChebAllxChallenge.lean": challenge,
    root / "scripts" / "PrintAxioms.lean": axioms_text,
    root / "comparator.json": comparator,
}
if "--check" in sys.argv:
    bad = [str(p) for p, t in targets.items() if not p.exists() or p.read_text() != t]
    if bad:
        sys.exit("out of date: " + ", ".join(bad))
    print("OK: ChebAllxChallenge.lean, scripts/PrintAxioms.lean, comparator.json are up to date "
          "(%d statements)" % len(names))
else:
    for p, t in targets.items():
        p.write_text(t)
    print("generated %d statements: %s" % (len(names), ", ".join(names)))
