#!/usr/bin/env python3
"""Generate RaceChallenge.lean from RaceChallengeDeps.lean (definitions) and RaceSolution.lean (statements).

RaceChallenge.lean = header + the definition layer of RaceChallengeDeps.lean inlined verbatim + every
theorem of RaceSolution.lean with its docstring and statement copied byte for byte and its proof
replaced by `sorry`.  Run from the project root:   python3 scripts/gen_challenge.py
With --check it only verifies that the committed RaceChallenge.lean is up to date (exit code 1 if not).
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
deps = (root / "RaceChallengeDeps.lean").read_text()
sol = (root / "RaceSolution.lean").read_text()

# definition layer: everything after `import Mathlib`
marker = "import Mathlib\n"
body = deps[deps.index(marker) + len(marker):].strip("\n")

# theorems: docstring + statement up to ` := by`, proof = following indented lines
pat = re.compile(r"(/--(?:.|\n)*?-/\ntheorem (\w+)(?:.|\n)*?) := by\n((?:  .*\n?)+)")
thms = pat.findall(sol)
if not thms:
    sys.exit("no theorems found in RaceSolution.lean")
# the `open`s under which RaceSolution.lean states the theorems
opens = "\n".join(l for l in sol.splitlines() if l.startswith("open "))

HEADER = '''/-
RaceChallenge.lean — the TRUSTED challenge module: WHAT IS CLAIMED.   (GENERATED FILE: see
scripts/gen_challenge.py; the definitions are inlined verbatim from RaceChallengeDeps.lean and the
statements are copied byte for byte from RaceSolution.lean, with every proof replaced by `sorry`.)

Machine-checked statements about a smoothed Chebyshev prime race modulo 4, conditional on an
explicit Riemann hypothesis for the single L-function L(s,χ₋₄):

  * `explicit_formula_zero_sum` — the explicit formula at shift 0, unconditional (a restatement of
    the Zeta23 library's `EF_lit_chi_L` in the notation below);
  * `grh_smoothed_prime_power_sum_bound`, `grh_smoothed_prime_power_sum_le_zero_sum` — stage S0 for
    every primitive Dirichlet character χ mod q > 1: under GRH for L(s,χ),
    ‖S(L) − Γ_L‖ ≤ Σ_ρ m_ρ ĝ(γ_ρ) for g = f ⋆ f̃ and every shift L beyond the support;
  * `grhFor_of_dirichlet_zeros_on_line` — the shape of the GRH hypothesis;
  * `chi4_isPrimitive`, `chi4_archWeight`, `grh_chi4_smoothed_prime_power_sum_bound` — S0 for χ₋₄
    in closed form, ‖S(L) − Γ_L‖ ≤ Re Γ_0 when supp g ⊂ (−log 3, log 3);
  * `prime_number_theorem_theta` — θ(x)/x → 1 (unconditional);
  * `grh_chi4_smoothed_race_two_sided`, `grh_chi4_smoothed_race` — stage S1: under GRH for
    L(s,χ₋₄), the primes-only smoothed sum P(L) = Σ_p χ₋₄(p) (log p) p^{-1/2} g(log p − L) satisfies
    ‖P(L) + ĝ(0)/2‖ ≤ Re Γ_0 + ε for all large L; hence P(L) < 0 for all large L whenever the
    explicit numerical inequality Re Γ_0 < ĝ(0)/2 holds for the chosen window (an explicit
    hypothesis of the theorem);
  * `chi4_primeSum_eq_chi4RaceSum`, `chi4_archTerm_zero_eq_chi4Gamma0`,
    `grh_chi4_smoothed_race_real_two_sided`, `grh_chi4_smoothed_race_real` — the same for a
    real-valued window, stated entirely in real terms (the headline).

This module imports ONLY Mathlib.  Every hypothesis is an explicit binder: there is no `axiom`.
RaceSolution.lean (untrusted) proves exactly these statements from RaceLib/ and the Zeta23 library.
The `sorry`s below are deliberate (this is the challenge side).
-/
import Mathlib

/-
The definitions below are inlined character for character from RaceChallengeDeps.lean (the trusted
Mathlib-only definition layer, which continues to exist for the Solution build), so that this
module's only import is Mathlib.
-/
section
'''

out = [HEADER, body, "\n\nend\n\n/-! ## The statements -/\n\n", opens, "\n"]
for stmt, name, _proof in thms:
    out.append("\n" + stmt + " := by\n  sorry\n")
text = "".join(out)

names = [n for _, n, _ in thms]
axioms_text = """/-
scripts/PrintAxioms.lean — axiom audit of the headline theorems (GENERATED by
scripts/gen_challenge.py):
    lake build RaceSolution && lake env lean scripts/PrintAxioms.lean
Every line must print exactly
    'X' depends on axioms: [propext, Classical.choice, Quot.sound]
(no sorryAx, no other axiom).  GRH and the numerical certificate are explicit hypotheses of the
theorems, visible in their statements; they are not axioms.
-/
import RaceSolution

""" + "".join(f"#print axioms {n}\n" for n in names)
import json
comparator_text = json.dumps({
    "challenge_module": "RaceChallenge",
    "solution_module": "RaceSolution",
    "theorem_names": names,
    "definition_names": [],
    "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
    "enable_nanoda": True,
}, indent=2) + "\n"

target = root / "RaceChallenge.lean"
aux = [(root / "scripts" / "PrintAxioms.lean", axioms_text), (root / "comparator.json", comparator_text)]
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != text:
        sys.exit("RaceChallenge.lean is NOT up to date with RaceChallengeDeps.lean / RaceSolution.lean")
    for path, content in aux:
        if not path.exists() or path.read_text() != content:
            sys.exit(f"{path.name} is NOT up to date")
    print(f"RaceChallenge.lean is up to date ({len(thms)} statements: {', '.join(n for _, n, _ in thms)})")
else:
    target.write_text(text)
    for path, content in aux:
        path.write_text(content)
    print(f"wrote RaceChallenge.lean ({len(thms)} statements: {', '.join(n for _, n, _ in thms)})")
