#!/usr/bin/env python3
"""Generate AllxChallenge.lean from AllxSolution.lean (statements) and the Mathlib-only definitions
`GRHFor`, `chi4` (inlined verbatim from ../lean-chebyshev/ChebLib/Race/Defs.lean) and
`primeCountingMod4` (inlined verbatim from AllxLib/Defs.lean).

AllxChallenge.lean = header + the three definitions + every theorem of AllxSolution.lean with its
docstring and statement copied byte for byte and its proof replaced by `sorry`.
Also regenerates scripts/PrintAxioms.lean and comparator.json.
Run from the project root:   python3 scripts/gen_challenge.py
With --check it only verifies that the committed files are up to date (exit code 1 if not).
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
race_defs = (root / ".." / "lean-chebyshev" / "ChebLib" / "Race" / "Defs.lean").read_text()
allx_defs = (root / "AllxLib" / "Defs.lean").read_text()
sol = (root / "AllxSolution.lean").read_text()


def grab(text, start):
    """The docstring + definition starting at the docstring that precedes `start`."""
    i = text.index(start)
    j = text.rindex("/--", 0, i)
    k = text.find("\n\n", i)
    if k < 0:
        k = len(text)
    return text[j:k].rstrip("\n")


def_grh = grab(race_defs, "def GRHFor")
def_chi4 = grab(race_defs, "def chi4 ")
def_count = grab(allx_defs, "noncomputable def primeCountingMod4")

pat = re.compile(r"(/--(?:.|\n)*?-/\ntheorem (\w+)(?:.|\n)*?) := by\n((?:  .*\n?)+)")
thms = pat.findall(sol)
if not thms:
    sys.exit("no theorems found in AllxSolution.lean")
opens = "\n".join(l for l in sol.splitlines() if l.startswith("open "))

HEADER = '''/-
AllxChallenge.lean — the TRUSTED challenge module: WHAT IS CLAIMED.   (GENERATED FILE: see
scripts/gen_challenge.py; the definitions `GRHFor`, `chi4` are inlined verbatim from
lean-chebyshev's ChebLib/Race/Defs.lean, `primeCountingMod4` from AllxLib/Defs.lean, and the
statements are copied byte for byte from AllxSolution.lean, with every proof replaced by `sorry`.)

THE CESÀRO MEAN OF CHEBYSHEV'S RACE IS POSITIVE AT EVERY x > 3, UNDER GRH FOR ONE L-FUNCTION.

  * `chebyshev_race_cesaro_pos` — the headline: if every zero of L(s,χ₋₄) in 0 < Re s < 1 has real
    part 1/2 (`GRHFor chi4`), then for EVERY real x > 3
        Σ_{p ≤ x} (−χ₋₄(p)) (1 − p/x) > 0        (−χ₋₄(p) = +1, −1, 0 for p ≡ 3, 1 mod 4, p = 2);
  * `chebyshev_race_cesaro_eq_integral` (no hypothesis) — that sum is (1/x) ∫₀ˣ (π(t;4,3) − π(t;4,1)) dt;
    `chebyshev_race_integral_pos` — hence the integral is positive for every x > 3 under GRH;
  * `chebyshev_race_theta1_pos` — Θ₁(t) = Σ_{p ≤ t} (−χ₋₄(p)) log p · (t − p) > 0 for every t > 3;
    `chebyshev_race_cesaro_lower_bound` — R(x) ≥ Θ₁(x)/(x log x);
  * `chebyshev_race_lead_inheritance` — for every x > 3: Σ_{p ≤ x} (−χ₋₄(p)) p ≥ 0 ⟹ π(x;4,1) < π(x;4,3);
  * `chebyshev_race_cone_lower_bound`, `chebyshev_race_cone_lead_inheritance` — the cone of weights
    m ≤ 0, m < m' ≤ 1: D_m(x) − x^{−(m'−m)} D_{m'}(x) ≥ (m'−m) x^{m−1} Θ₁(x)/log x, hence
    D_{m'}(x) ≥ 0 ⟹ D_m(x) > 0, for every x > 3  (D_m(x) = Σ_{p ≤ x} (−χ₋₄(p)) p^m);
  * `chebyshev_race_cesaro_pos_of_le` (no hypothesis) — the headline inequality for 3 < x ≤ 10⁷
    (kernel-checked);
  * `grh_chi4_psi1_le` — ψ₁(t,χ₋₄) ≤ (27/100)(t+1)^{3/2} + 4t + log t + 4 + (1/3) log(t+1), t ≥ 2;
  * `chebyshev_race_sum_eq_counts`, `neg_chi4_natCast`, `grhFor_of_dirichlet_zeros_on_line` — the
    conventions: Σ_{p ≤ x} (−χ₋₄(p)) = π(x;4,3) − π(x;4,1); the sign of −χ₋₄; the shape of GRH.

This module imports ONLY Mathlib.  Every hypothesis is an explicit binder: there is no `axiom`.
AllxSolution.lean (untrusted) proves exactly these statements from AllxLib/, lean-chebyshev's
ChebLib/ and the Zeta23 library.  The `sorry`s below are deliberate (this is the challenge side).
-/
import Mathlib
'''

out = [HEADER]
out.append("/-! ## Definitions (inlined verbatim) -/\n")
out.append(def_grh + "\n")
out.append(def_chi4 + "\n")
out.append(def_count + "\n")
out.append(opens + "\n")
out.append("/-! ## Statements -/\n")
names = []
for stmt, name, _proof in thms:
    names.append(name)
    out.append(stmt + " := by\n  sorry\n")
challenge = "\n".join(out)

axioms = ['''/-
scripts/PrintAxioms.lean — axiom audit of the headline theorems (GENERATED by
scripts/gen_challenge.py):
    lake build AllxSolution && lake env lean scripts/PrintAxioms.lean
Every line must print exactly
    'X' depends on axioms: [propext, Classical.choice, Quot.sound]
(no sorryAx, no Lean.ofReduceBool, no other axiom).  GRH for L(s,χ₋₄) is an explicit hypothesis of
the theorems, visible in their statements; it is not an axiom.
-/
import AllxSolution
''']
axioms += ["#print axioms %s" % n for n in names]
axioms_text = "\n".join(axioms) + "\n"

comparator = json.dumps({
    "challenge_module": "AllxChallenge",
    "solution_module": "AllxSolution",
    "theorem_names": names,
    "definition_names": ["GRHFor", "chi4", "primeCountingMod4"],
    "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
    "enable_nanoda": True,
}, indent=2) + "\n"

targets = {
    root / "AllxChallenge.lean": challenge,
    root / "scripts" / "PrintAxioms.lean": axioms_text,
    root / "comparator.json": comparator,
}
if "--check" in sys.argv:
    bad = [str(p) for p, t in targets.items() if not p.exists() or p.read_text() != t]
    if bad:
        sys.exit("out of date: " + ", ".join(bad))
    print("OK: AllxChallenge.lean, scripts/PrintAxioms.lean, comparator.json are up to date "
          "(%d statements)" % len(names))
else:
    for p, t in targets.items():
        p.write_text(t)
    print("generated %d statements: %s" % (len(names), ", ".join(names)))
