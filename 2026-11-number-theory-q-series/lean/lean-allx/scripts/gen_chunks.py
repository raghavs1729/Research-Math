#!/usr/bin/env python3
"""Generator for the kernel-checked finite verification (AllxLib/Finite).

Replicates the integer scan of `AllxLib/Finite/Defs.lean` exactly (same state
`(a, up, um, vp, vm)`, same exponent check `2^a <= n^256 < 2^(a+1)`) and emits

  AllxLib/Finite/ChunksXX.lean   chunk theorems  cJ : runChunk n0 K B <state_J> = (true, <state_{J+1}>)
                                 (each proved by `decide +kernel`), PER_FILE per file
  AllxLib/Finite/ChainXX.lean    R_{J+1} : Good (n0+K) <state_{J+1}> := Good.step R_J cJ   (one-liners)
  AllxLib/Finite/Chain.lean      theta1_cw_nat_pos : forall k, 4 <= k -> k <= N -> 0 < Theta1 cw k

The numerals are NOT trusted: each chunk theorem is checked by the Lean kernel, and the
invariant is transported by `Allx.Good.step`.

usage:  python3 scripts/gen_chunks.py N [K] [PER_FILE]     (default K = 10000, PER_FILE = 125)
"""
import sys, os, math
import numpy as np

M = 256
N = int(float(sys.argv[1]))
K = int(sys.argv[2]) if len(sys.argv) > 2 else 10000
PER_FILE = int(sys.argv[3]) if len(sys.argv) > 3 else 125
assert N % K == 0
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "AllxLib", "Finite")

# primes up to N (ordinary sieve; only used to predict what the kernel will compute)
sieve = np.ones(N + 2, dtype=bool); sieve[:2] = False
for i in range(2, math.isqrt(N + 1) + 1):
    if sieve[i]: sieve[i * i::i] = False

def lift_all(P, a):
    """Same as `Allx.liftAll`."""
    if not (1 << (a + 1)) <= P:
        return a
    for d in (256, 128, 64, 32, 16, 8, 4, 2, 1):
        if (1 << (a + d)) <= P: a += d
    return a

def fmt(st):
    return "(%s)" % ", ".join(str(x) for x in st)

nchunks = N // K
a = up = um = vp = vm = 0
chunks = []     # (n0, Kj, B, state_in, state_out)
for j in range(nchunks):
    n0 = j * K
    Kj = K + 1 if j == nchunks - 1 else K      # the last chunk also covers n = N
    B = math.isqrt(n0 + Kj - 1) + 1            # least B with B*B >= n0 + Kj
    assert B * B >= n0 + Kj and B >= 2
    st_in = (a, up, um, vp, vm)
    for n in range(n0, n0 + Kj):
        vp += up; vm += um
        assert n < 4 or vm < vp, ("positivity fails at", n)
        if sieve[n]:
            P = n ** M
            a = lift_all(P, a)
            assert (1 << a) <= P < (1 << (a + 1)), ("lifting fails at", n)
            r = n % 4
            if r == 3: up += a
            elif r == 1: um += a + 1
    chunks.append((n0, Kj, B, st_in, (a, up, um, vp, vm)))
    # the next chunk starts at n0 + K: undo nothing (for the last chunk there is no next one)
print("scan ok up to", N, "final state", (a, up, um, vp, vm), file=sys.stderr)

nfiles = (nchunks + PER_FILE - 1) // PER_FILE
for f in range(nfiles):
    lines = ["/- Generated by scripts/gen_chunks.py (N = %d, K = %d). Do not edit. -/" % (N, K),
             "import AllxLib.Finite.Defs", "",
             "set_option maxRecDepth 1000000",
             "-- one kernel evaluation at a time (asynchronous elaboration would run all the",
             "-- `decide +kernel` checks of the file concurrently and exhaust the memory)",
             "set_option Elab.async false", "",
             "namespace Allx.Chunks", ""]
    for j in range(f * PER_FILE, min(nchunks, (f + 1) * PER_FILE)):
        n0, Kj, B, si, so = chunks[j]
        lines.append("theorem c%d : runChunk %d %d %d %s =\n    (true, %s) := by decide +kernel"
                     % (j, n0, Kj, B, " ".join(str(x) for x in si), ", ".join(str(x) for x in so)))
    lines += ["", "end Allx.Chunks", ""]
    with open(os.path.join(OUT, "Chunks%02d.lean" % (f + 1)), "w") as fh:
        fh.write("\n".join(lines))

# chain files: ChainXX imports Scan, ChunksXX and Chain(XX-1)
for f in range(nfiles):
    lines = ["/- Generated by scripts/gen_chunks.py (N = %d, K = %d). Do not edit. -/" % (N, K),
             "import AllxLib.Finite.Scan", "import AllxLib.Finite.Chunks%02d" % (f + 1)]
    if f > 0: lines.append("import AllxLib.Finite.Chain%02d" % f)
    lines += ["", "namespace Allx.Chunks", ""]
    if f == 0:
        lines.append("theorem R0 : Good 0 (0, 0, 0, 0, 0) := good_zero")
    for j in range(f * PER_FILE, min(nchunks, (f + 1) * PER_FILE)):
        n0, Kj, B, si, so = chunks[j]
        lines.append("theorem R%d : Good %d %s :=\n    Good.step (n0 := %d) (K := %d) R%d c%d"
                     % (j + 1, n0 + Kj, fmt(so), n0, Kj, j, j))
    lines += ["", "end Allx.Chunks", ""]
    with open(os.path.join(OUT, "Chain%02d.lean" % (f + 1)), "w") as fh:
        fh.write("\n".join(lines))

with open(os.path.join(OUT, "Chain.lean"), "w") as fh:
    fh.write("""/- Generated by scripts/gen_chunks.py (N = %d, K = %d). Do not edit. -/
import AllxLib.Finite.Chain%02d

namespace Allx

/-- `Θ₁(k) > 0` for the log-weighted coefficients at every integer `4 ≤ k ≤ %d`
(chained kernel checks of %d chunks). -/
theorem theta1_cw_nat_pos {k : ℕ} (h4 : 4 ≤ k) (hk : k ≤ %d) : 0 < Coupling.Theta1 cw k :=
  Chunks.R%d.2 k h4 (by omega)

end Allx
""" % (N, K, nfiles, N, nchunks, N, nchunks))
print("wrote %d chunk files, %d chunks" % (nfiles, nchunks), file=sys.stderr)
