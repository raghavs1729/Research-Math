def wrap(items, indent, width=96):
    lines, cur = [], indent
    for it in items:
        if len(cur) + len(it) > width and cur.strip():
            lines.append(cur.rstrip())
            cur = indent
        cur += it
    lines.append(cur.rstrip())
    return "\n".join(lines)


def head_expr_wrapped(s, N, indent):
    parts = []
    for i, (n, sg, p) in enumerate(head(s, N)):
        t = f"log {p} / {n} ^ {s}"
        if i == 0:
            parts.append(t if sg > 0 else f"-({t})")
        else:
            parts.append((" + " if sg > 0 else " - ") + t)
    return wrap(parts, indent)


