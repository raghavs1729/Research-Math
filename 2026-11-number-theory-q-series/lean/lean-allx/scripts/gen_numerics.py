#!/usr/bin/env python3
"""Generator for `AllxLib/Analytic/Numerics.lean`.

Usage:  python3 scripts/gen_numerics.py [M] > AllxLib/Analytic/Numerics.lean

`M` (default 47, must be `3 mod 4`) is the length of the head of the series
`A = sum_n Lambda(n) (-chi_{-4}(n)) / n^2` that is evaluated exactly; the tail is bounded by
`(log M + 1)/(4M)`.  The script picks rational bounds `log p <= (m/k) log 2` (from
`p^k <= 2^m`) resp. `>=`, checks with exact rational arithmetic that the final linear
inequality closes, and prints the Lean file (static part + generated part).
"""
import sys
from fractions import Fraction as F
from math import log

M = int(sys.argv[1]) if len(sys.argv) > 1 else 47
assert M % 4 == 3 and M >= 15
KB = 13          # the head of B is n < KB, KB = 1 mod 4, KB >= 13
assert KB % 4 == 1 and KB >= 13 and KB <= M
KMAX = 60        # maximal exponent k in p^k <= 2^m
HN = 255         # gamma > H_HN - log(HN + 1)
HSC = 10 ** 9


def is_prime(n):
    return n >= 2 and all(n % d for d in range(2, int(n ** 0.5) + 1))


def classify(n):
    """('even',) | ('one',) | ('pp', p, k) | ('npp', p, q)"""
    if n % 2 == 0:
        return ('even',)
    if n == 1:
        return ('one',)
    ps = [p for p in range(2, n + 1) if is_prime(p) and n % p == 0]
    if len(ps) == 1:
        p, k, m = ps[0], 0, n
        while m > 1:
            m //= p
            k += 1
        return ('pp', p, k)
    return ('npp', ps[0], ps[1])


def best_upper(p):
    """(k, m) with p^k <= 2^m, k <= KMAX, m/k minimal."""
    best = None
    for k in range(1, KMAX + 1):
        m = 0
        while 2 ** m < p ** k:
            m += 1
        if best is None or F(m, k) < F(best[1], best[0]):
            best = (k, m)
    return best


def best_lower(p):
    """(k, m) with 2^m <= p^k, k <= KMAX, m/k maximal."""
    best = None
    for k in range(1, KMAX + 1):
        m = 0
        while 2 ** (m + 1) <= p ** k:
            m += 1
        if best is None or F(m, k) > F(best[1], best[0]):
            best = (k, m)
    return best


# ---------------------------------------------------------------------------------------
# head terms
# ---------------------------------------------------------------------------------------
def head(s, N):
    """list of (n, sign, p) with cTerm s n = sign * log p / n^s, for n < N."""
    out = []
    for n in range(N):
        c = classify(n)
        if c[0] == 'pp':
            out.append((n, 1 if n % 4 == 3 else -1, c[1]))
    return out


headA = head(2, M + 1)
headB = head(3, KB)
primes = sorted({p for (_, _, p) in headA} | {p for (_, _, p) in headB} | {M})
assert is_prime(M), "M must be prime (so that log M is one of the atoms)"

# ---------------------------------------------------------------------------------------
# exact verification of the final linear inequality
#   LHS = 17/8 - 3/4 gamma - 3/4 log pi - 5/4 log 2 + 11/4 A - 5/4 B
#   A <= headA + (log M + 1)/(4M),   B >= headB - (2 log 3 + 1)/(36 * KB)   (pot 9 / KB)
# ---------------------------------------------------------------------------------------
cA, cB = F(11, 4), F(5, 4)
coef = {p: F(0) for p in primes}
const = F(17, 8)
for (n, sg, p) in headA:
    coef[p] += cA * sg * F(1, n ** 2)
coef[M] += cA * F(1, 4 * M)
const += cA * F(1, 4 * M)
for (n, sg, p) in headB:
    coef[p] -= cB * sg * F(1, n ** 3)
coef[3] += cB * F(2, 36 * KB)
const += cB * F(1, 36 * KB)

L2LO, L2HI = F(6931471803, 10 ** 10), F(6931471808, 10 ** 10)
HSUM = sum(HSC // k for k in range(1, HN + 1))
assert HN + 1 == 2 ** 8
GAMMA_LO = F(5752, 10000)
assert GAMMA_LO <= F(HSUM, HSC) - 8 * L2HI
PI_K, PI_M = 20, 33
assert F(31415, 10000) ** PI_K >= 2 ** PI_M

bounds = {}
c2 = F(-5, 4) - F(3, 4) * F(PI_M, PI_K)
const -= F(3, 4) * GAMMA_LO
for p in primes:
    if coef[p] >= 0:
        k, m = best_upper(p)
        assert p ** k <= 2 ** m
        bounds[p] = ('le', k, m)
    else:
        k, m = best_lower(p)
        assert 2 ** m <= p ** k
        bounds[p] = ('ge', k, m)
    c2 += coef[p] * F(m, k)
total = const + c2 * (L2HI if c2 >= 0 else L2LO)
assert total < F(27, 100), float(total)
sys.stderr.write(f"M = {M}: certified upper bound {float(total):.6f} < 0.27\n")

# tsum_vonMangoldt_div_sq_le check: log 2/4 + log 3/9 + (log 3 + 1)/3, log 3 <= 8/5 log 2
assert L2HI / 4 + F(8, 5) * L2HI * (F(1, 9) + F(1, 3)) + F(1, 3) <= F(7, 6)

