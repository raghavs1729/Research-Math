"""Independent Dirichlet-character construction for the second audit (no use of the
author's code, no use of flint's dirichlet_group).  Characters are built from the
CRT decomposition of (Z/q)^* into cyclic factors; values are stored as exact
fractions of a turn (chi(n) = exp(2 pi i * val[n]), val in Q/Z) or None if gcd(n,q)>1.
"""
from fractions import Fraction
from math import gcd
from itertools import product
import sympy


def _cyclic_components(q):
    """Return list of (modulus m, generator g, order o, embed) where (Z/q)^* is the
    product of cyclic groups generated by elements congruent to g mod m and 1 mod q/m
    (for 2-power parts there may be two components)."""
    comps = []
    for p, e in sympy.factorint(q).items():
        pe = p ** e
        rest = q // pe
        def lift(x, pe=pe, rest=rest):
            # element congruent to x mod pe and 1 mod rest
            return int(sympy.ntheory.modular.crt([pe, rest], [x % pe, 1])[0]) if rest > 1 else x % pe
        if p == 2:
            if e == 1:
                continue
            if e == 2:
                comps.append((pe, lift(3), 2, 'm1'))          # -1 generates
            else:
                comps.append((pe, lift(pe - 1), 2, 'm1'))     # -1
                comps.append((pe, lift(5), 2 ** (e - 2), 'five'))
        else:
            g = sympy.primitive_root(pe)
            comps.append((pe, lift(g), (p - 1) * p ** (e - 1), 'cyc'))
    return comps


def _dlog_tables(q):
    """For every unit n mod q, its exponent vector w.r.t. the components."""
    comps = _cyclic_components(q)
    table = {}
    orders = [c[2] for c in comps]
    gens = [c[1] for c in comps]
    for exps in product(*[range(o) for o in orders]):
        n = 1
        for g, k in zip(gens, exps):
            n = n * pow(g, k, q) % q
        table[n] = exps
    units = [n for n in range(1, q + 1) if gcd(n, q) == 1] if q > 1 else [0]
    if q == 1:
        return [], {0: ()}
    assert len(table) == len(units), (q, len(table), len(units))
    return orders, table


def characters(q):
    """All characters mod q as dicts n -> Fraction (turns) for units, None otherwise.
    Returns list of value lists indexed 0..q-1."""
    if q == 1:
        return [[Fraction(0)]]
    orders, table = _dlog_tables(q)
    chars = []
    for js in product(*[range(o) for o in orders]):
        vals = [None] * q
        for n, exps in table.items():
            v = sum(Fraction(j * k, o) for j, k, o in zip(js, exps, orders))
            vals[n % q] = v - (v.numerator // v.denominator)
        chars.append(vals)
    return chars


def conductor(vals, q):
    if q == 1:
        return 1
    for d in sorted(sympy.divisors(q)):
        ok = True
        for n in range(1, q):
            if vals[n] is not None and n % d == 1 % d and vals[n] != 0:
                ok = False
                break
        if ok:
            return d
    return q


def primitive_characters(f):
    return [v for v in characters(f) if conductor(v, f) == f]


def parity(vals, q):
    if q <= 2:
        return 0
    return 0 if vals[q - 1] == 0 else 1


def order(vals):
    from math import lcm
    o = 1
    for v in vals:
        if v is not None:
            o = lcm(o, v.denominator)
    return o


if __name__ == '__main__':
    for f in [3, 4, 5, 8, 12, 15, 16, 20, 24, 400]:
        P = primitive_characters(f)
        print(f, len(characters(f)), 'primitive:', len(P),
              'parities', sum(parity(v, f) for v in P))
