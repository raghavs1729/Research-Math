rows = []
for i in sorted(stm, key=key):
    s, src, note = stm[i]
    st = STATUS.get(i, 'open as far as determined')
    wz = ('exact match: ' + ', '.join(sorted(match[i]))) if i in match else (('signature hits: ' + ', '.join(sorted(hits[i]))) if i in hits else 'no signature hit in the scanned box')
    rows.append((i, s, src, digits.get(i, '?'), wz, st))
